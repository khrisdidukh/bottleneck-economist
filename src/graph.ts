// Teamwork Graph connector: publishes each project's bottleneck report into the Teamwork Graph as an
// atlassian:document, associated with the Jira work items that are waiting at the bottleneck right now.
// Result: Rovo Search, Rovo Chat and any agent that reads the graph find "where our work waits and what
// fixing it is worth" next to the very issues that are stuck — context, not another dashboard.
import api, { route } from '@forge/api';
import { kvs } from '@forge/kvs';
import { graph, types } from '@forge/teamwork-graph';
import { randomUUID } from 'node:crypto';
import { compact, fmtMoney, type Report } from './engine/report';

export type Connection = { connectionId: string; projects: string[]; includeDemo: boolean; taskId: string };
const CONNECTIONS = 'tg:connections';

export async function connections(): Promise<Connection[]> {
  return (await kvs.get<Connection[]>(CONNECTIONS)) ?? [];
}
async function saveConnections(list: Connection[]) {
  await kvs.set(CONNECTIONS, list);
}

let siteUrl: string | undefined;
async function baseUrl(): Promise<string> {
  if (siteUrl) return siteUrl;
  const res = await api.asApp().requestJira(route`/rest/api/3/serverInfo`, { headers: { Accept: 'application/json' } });
  siteUrl = res.ok ? String((await res.json()).baseUrl ?? '').replace(/\/$/, '') : '';
  return siteUrl;
}

/** Plain-text report body for search and for Rovo to quote. */
export function reportText(r: Report, stuck: string[]): string {
  const c = compact(r);
  const lines = [
    `Bottleneck report for ${r.project}.`,
    `Period: ${new Date(r.flow.window.from).toISOString().slice(0, 10)} to ${new Date(r.flow.window.to).toISOString().slice(0, 10)}.`,
    c.headline,
    `Delivered per week: ${c.flow.deliveredPerWeek} (capacity ${c.flow.systemCapacityPerWeek}, arriving ${c.flow.arrivingPerWeek}). Lead time: mean ${c.flow.leadTimeDays.mean} days, median ${c.flow.leadTimeDays.median}. Flow efficiency ${c.flow.flowEfficiency}.`,
    `Where lead time goes: ${c.whereLeadTimeGoes.map((s) => `${s.status} ${s.share} (${s.kind})`).join('; ')}.`,
    ...c.constraints.slice(0, 1).map((x) => `Constraint: work waits in "${x.waitIn}" for ${x.waitsFor}; ${x.type} constraint, ${x.leadShare} of lead time. Evidence: ${x.evidence.join('; ')}.`),
    c.adizes ? `Adizes (PAEI): missing role ${c.adizes.missingRole}. ${c.adizes.meaning}` : '',
    `Options, real value vs value only on paper: ${c.options.slice(0, 5).map((o) => `${o.action}: ${o.realValuePerYear}/year real${o.paperValuePerYear ? `, ${o.paperValuePerYear} on paper` : ''} (${o.verdict})`).join('; ')}.`,
    stuck.length ? `Work items waiting at the bottleneck now: ${stuck.slice(0, 30).join(', ')}${stuck.length > 30 ? ` and ${stuck.length - 30} more` : ''}.` : '',
    `Money assumptions: ${fmtMoney(r.money.hourlyCost, r.money.currency)}/hour, ${fmtMoney(r.money.valuePerItem, r.money.currency)} per delivered item.`,
    'Generated by Bottleneck Economist (Forge app). Figures are aggregates; people are pseudonymised.',
  ];
  return lines.filter(Boolean).join('\n');
}

function documentFor(r: Report, stuck: string[], url: string) {
  const c = r.constraints[0];
  const now = new Date().toISOString();
  return {
    schemaVersion: '1.0',
    id: `bottleneck-report-${r.source === 'demo' ? 'demo-cassandra' : r.project.toLowerCase()}`,
    updateSequenceNumber: Date.now(),
    displayName: `Bottleneck report: ${r.source === 'demo' ? 'Apache Cassandra (demo)' : r.project}${c ? `, work waits in "${c.status}"` : ''}`,
    description: r.headline.slice(0, 250),
    url,
    createdAt: r.generatedAt,
    lastUpdatedAt: now,
    permissions: [{ accessControls: [{ principals: [{ type: 'ATLASSIAN_WORKSPACE' as const }] }] }],
    ...(stuck.length ? { associations: { lastUpdatedAt: now, set: [{ associationType: 'issueIdOrKeys', values: stuck.slice(0, 100) }] } } : {}),
    'atlassian:document': {
      type: { category: 'DOCUMENT' as const, mimeType: 'text/plain' },
      content: { mimeType: 'text/plain', text: reportText(r, stuck) },
      labels: ['bottleneck-economist', 'theory-of-constraints', r.source === 'demo' ? 'demo' : r.project.toLowerCase()],
    },
  };
}

/** Push one project's report to every connection that follows it. Returns accepted/rejected counts. */
export async function publishReport(r: Report, stuck: string[]) {
  if (!r.constraints.length) return { published: 0, connections: 0, reason: 'no constraint found' };
  const list = await connections();
  const targets = list.filter((x) => (r.source === 'demo' ? x.includeDemo : x.projects.includes(r.project)));
  if (!targets.length) return { published: 0, connections: 0 };
  const base = await baseUrl();
  const url = r.source === 'demo' ? `${base}/jira/apps` : `${base}/browse/${r.project}`;
  const doc = documentFor(r, stuck, url || 'https://developer.atlassian.com');
  let accepted = 0;
  const errors: string[] = [];
  const errorsFor: (string | undefined)[] = [];
  for (const t of targets) {
    const res: any = await graph.setObjects({ connectionId: t.connectionId, objects: [doc as any] });
    const rejected = res?.results?.rejected ?? [];
    const n = res?.results?.accepted?.length ?? 0;
    accepted += n;
    errorsFor.push(res?.success ? undefined : String(res?.error ?? ''));
    if (!res?.success || rejected.length) {
      errors.push(String(res?.error ?? JSON.stringify(rejected).slice(0, 300)));
      console.error('[graph] setObjects failed', { project: r.project, connectionId: t.connectionId, rejected, error: res?.error });
    } else console.log('[graph] published', { project: r.project, connectionId: t.connectionId, accepted: n });
  }
  const dead = targets.filter((t, i) => DEAD.test(errorsFor[i] ?? ''));
  if (dead.length) await saveConnections((await connections()).filter((x) => !dead.some((d) => d.connectionId === x.connectionId)));
  const live = targets.length - dead.length;
  const key = r.source === 'demo' ? 'DEMO' : r.project;
  const prev = await lastPublished(key);
  const status = accepted
    ? { at: new Date().toISOString(), accepted, connections: live }
    : { ...(prev ?? { at: '', accepted: 0, connections: live }), lastError: errors[0]?.slice(0, 200) };
  await kvs.set(pubKey(key), status);
  return { published: accepted, connections: live, errors: accepted ? [] : errors };
}

const pubKey = (p: string) => `tg:published:${p.replace(/[^A-Za-z0-9_-]/g, '_').slice(0, 80)}`;
export async function lastPublished(project: string) {
  return kvs.get<{ at: string; accepted: number; connections: number; lastError?: string }>(pubKey(project));
}

const parseProjects = (s?: string) => String(s ?? '').toUpperCase().split(/[\s,;]+/).filter((p) => /^[A-Z][A-Z0-9_]{0,19}$/.test(p)).slice(0, 20);
const truthy = (s?: string) => /^(true|yes|1|on)$/i.test(String(s ?? 'true'));

export type Sync = (conn: Connection, mode: 'quick' | 'full') => Promise<void>;

/**
 * onConnectionChange: the admin connected, edited or removed the connector in Atlassian Administration.
 * Teamwork Graph writes are accepted only inside the connector's own invocations (this handler and the
 * task runner), so the reports that are ready are published here, and the daily task re-analyses.
 */
export async function handleConnectionChange(request: any, sync: Sync) {
  const { action, connectionId, configProperties } = request ?? {};
  const list = await connections();
  console.log('[graph] connection change', { action, connectionId, known: list.length });
  if (action === 'DELETED') {
    await saveConnections(list.filter((x) => x.connectionId !== connectionId));
    return { success: true };
  }
  const prev = list.find((x) => x.connectionId === connectionId);
  if (action === 'CREATED') await pruneInvalid(list.filter((x) => x.connectionId !== connectionId));
  const current = await connections();
  const conn: Connection = {
    connectionId,
    projects: parseProjects(configProperties?.projects),
    includeDemo: truthy(configProperties?.includeDemo),
    taskId: prev?.taskId ?? randomUUID(),
  };
  await saveConnections([...current.filter((x) => x.connectionId !== connectionId), conn]);
  try { await sync(conn, 'quick'); } catch (e) { console.error('[graph] initial publish failed', e); }
  const sched: any = await graph.scheduleOrUpdateTask({
    connectionId,
    task: { taskType: types.FORGE_TASK_TYPES.ENTITY_INGESTION_FULL, taskId: conn.taskId },
    scheduleInterval: { value: 1, timeUnit: 'days' },
  });
  if (sched?.error) console.error('[graph] scheduleOrUpdateTask failed', { connectionId, error: sched.error, response: JSON.stringify(sched).slice(0, 500) });
  else console.log('[graph] task scheduled', { connectionId, response: JSON.stringify(sched).slice(0, 300) });
  return { success: true };
}

const DEAD = /invalid connection|connection not found/i;
/** Forget connections the platform no longer accepts (for example removed while the app was offline). */
async function pruneInvalid(others: Connection[]) {
  const invalid: string[] = [];
  for (const c of others) {
    const res: any = await graph.getObjectByExternalId({ connectionId: c.connectionId, objectType: 'atlassian:document', externalId: 'probe' } as any).catch((e: any) => ({ error: String(e) }));
    if (DEAD.test(String(res?.error ?? ''))) invalid.push(c.connectionId);
  }
  if (invalid.length) {
    console.log('[graph] pruning invalid connections', invalid);
    await saveConnections((await connections()).filter((x) => !invalid.includes(x.connectionId)));
  }
}

export function validateConnection(request: any) {
  const projects = parseProjects(request?.configProperties?.projects);
  if (!projects.length && !truthy(request?.configProperties?.includeDemo))
    return { success: false, message: 'Add at least one Jira project key (for example ENG, OPS) or turn on the demo report.' };
  return { success: true, message: `Bottleneck reports will be published for ${projects.length ? projects.join(', ') : 'the demo project'}.` };
}

/** Daily orchestration run: re-analyse each followed project and publish the fresh reports. */
export async function handleTask(request: any, sync: Sync) {
  const { taskId, scanId, taskExecutionId, connectionId } = request ?? {};
  const report = (status: 'success' | 'failure', failureReason?: any) =>
    graph.updateTaskStatus({ scanId, taskExecutionId, connectionId, status, task: { taskId }, ...(failureReason ? { failureReason } : {}) } as any);
  const conn = (await connections()).find((x) => x.connectionId === connectionId);
  if (!conn) { await report('failure', 'ENTITY_NOT_FOUND'); return { success: false, message: 'Unknown connection' }; }
  // at-least-once delivery: one run per scan
  const doneKey = `tg:scan:${scanId}`;
  if (await kvs.get(doneKey)) { await report('success'); return { success: true, message: 'Duplicate delivery' }; }
  try {
    await sync(conn, 'full');
    await kvs.set(doneKey, { at: new Date().toISOString() });
    await report('success');
    return { success: true };
  } catch (e: any) {
    console.error('[graph] task failed', e);
    await report('failure', 'RETRYABLE_ERROR');
    return { success: false, message: String(e?.message ?? e) };
  }
}
